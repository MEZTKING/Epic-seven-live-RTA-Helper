#!/usr/bin/env node
/*
 * Regenerates js/sources/fribbels-data.js: hero base stats (6-star, fully
 * awakened, level 60) and the artifact name list, from the data the RexQian fork
 * of the Fribbels optimizer uses (S3 bucket, falling back to the fork's GitHub
 * copy). Kept as its own source ('fribbels-data').
 *
 *   node tools/update-fribbels-data.js                       # download
 *   node tools/update-fribbels-data.js herodata.json artifactdata.json
 */
const fs = require('fs');
const path = require('path');
const { normalizeHeroStats, normalizeArtifacts, HERO_STATS_URL, ARTIFACT_URL, HERO_STATS_FALLBACK, ARTIFACT_FALLBACK } = require('../js/gear.js');

async function get(file, url, fallback) {
  if (file) return JSON.parse(fs.readFileSync(file, 'utf8'));
  try {
    const r = await fetch(url);
    if (!r.ok) throw new Error('HTTP ' + r.status);
    return await r.json();
  } catch (e) {
    console.warn(`Primary source failed (${e.message}); using the RexQian fork's GitHub copy.`);
    return (await fetch(fallback)).json();
  }
}
async function main() {
  const stats = normalizeHeroStats(await get(process.argv[2], HERO_STATS_URL, HERO_STATS_FALLBACK));
  const artifacts = normalizeArtifacts(await get(process.argv[3], ARTIFACT_URL, ARTIFACT_FALLBACK));
  if (Object.keys(stats).length < 100 || artifacts.length < 50) throw new Error('Data looks incomplete — not overwriting.');
  const out = path.join(__dirname, '..', 'js', 'sources', 'fribbels-data.js');
  const snapshot = { source: 'fribbels-data', fork: 'RexQian/Fribbels-Epic-7-Optimizer', urls: [HERO_STATS_URL, ARTIFACT_URL], fetchedAt: new Date().toISOString(), stats, artifacts };
  fs.writeFileSync(
    out,
    '/* AUTO-GENERATED by tools/update-fribbels-data.js — do not edit by hand. */\n' +
      '(function (root) {\n' +
      `  const snapshot = ${JSON.stringify(snapshot)};\n` +
      "  if (typeof module !== 'undefined' && module.exports) module.exports = snapshot;\n" +
      '  else (root.RTASources = root.RTASources || {}).fribbelsSnapshot = snapshot;\n' +
      "})(typeof window !== 'undefined' ? window : globalThis);\n",
  );
  console.log(`Wrote ${Object.keys(stats).length} hero stat blocks and ${artifacts.length} artifacts`);
}
main().catch((e) => {
  console.error(e.message);
  process.exit(1);
});
