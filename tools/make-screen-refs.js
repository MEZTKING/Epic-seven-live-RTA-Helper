#!/usr/bin/env node
/*
 * Builds js/sources/screen-refs.js: BUILT-IN screen signatures (32×18 fingerprints, js/screens.js) made from real
 * screenshots, so these screens are recognised without anyone teaching them. Uses the app's own browser code.
 * Only screens whose look doesn't depend on the battle background belong here (a full-screen menu/dialog), e.g. the
 * pre-ban picker. Run: node tools/make-screen-refs.js
 */
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');
const ROOT = path.join(__dirname, '..');
const SHOTS = [
  { screen: 'rta-lobby', file: 'tests/fixtures/screens/steam-rta-menu.png' },
  { screen: 'rta-found', file: 'tests/fixtures/screens/steam-rta-match-found.png' },
  { screen: 'rta-intro', file: 'tests/fixtures/screens/steam-rta-match-start.png' },
  { screen: 'rta-preban-pick', file: 'tests/fixtures/screens/steam-rta-preban-select.png' },
  { screen: 'rta-preban-pick', file: 'tests/fixtures/screens/steam-rta-preban-select2.png' },
  { screen: 'rta-draft', file: 'tests/fixtures/screens/steam-rta-ban.png' },
  // Guild War (owner's files 2026-11-13; maps/overview/battle blurred so no names are readable: a 32x18 signature is unaffected)
  { screen: 'gw-overview', file: 'tests/fixtures/screens/steam-gw-overview-blurred.png' },
  { screen: 'gw-map', file: 'tests/fixtures/screens/steam-gw-map1-blurred.png' },
  { screen: 'gw-map', file: 'tests/fixtures/screens/steam-gw-map2-blurred.png' },
  { screen: 'gw-enemy', file: 'tests/fixtures/screens/steam-gw-enemy.png' },
  { screen: 'gw-battle', file: 'tests/fixtures/screens/steam-gw-battle-blurred.png' },
];

(async () => {
  const b = await chromium.launch();
  const p = await b.newPage();
  await p.setContent('<body></body>');
  await p.addScriptTag({ path: path.join(ROOT, 'js/screens.js') });
  const refs = [];
  for (const s of SHOTS) {
    const img = 'data:image/png;base64,' + fs.readFileSync(path.join(ROOT, s.file)).toString('base64');
    const fp = await p.evaluate(async (img) => {
      const S = window.RTAScreens;
      const im = new Image();
      await new Promise((r) => { im.onload = r; im.src = img; });
      const c = document.createElement('canvas');
      c.width = S.W;
      c.height = S.H;
      const x = c.getContext('2d');
      x.drawImage(im, 0, 0, S.W, S.H);
      return Array.from(S.fingerprint(x.getImageData(0, 0, S.W, S.H).data), (v) => Math.round(v * 10000) / 10000);
    }, img);
    refs.push({ screen: s.screen, fp, from: path.basename(s.file), builtIn: true });
  }
  await b.close();
  const out = `/* AUTO-GENERATED by tools/make-screen-refs.js — built-in screen signatures from real screenshots. */
(function (root) {
  const refs = ${JSON.stringify(refs)};
  if (typeof module !== 'undefined' && module.exports) module.exports = refs;
  else (root.RTASources = root.RTASources || {}).screenRefs = refs;
})(typeof window !== 'undefined' ? window : globalThis);
`;
  fs.writeFileSync(path.join(ROOT, 'js/sources/screen-refs.js'), out);
  console.log('wrote js/sources/screen-refs.js:', refs.map((r) => r.screen).join(', '));
})();
