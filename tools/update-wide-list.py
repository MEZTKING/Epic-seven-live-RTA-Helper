#!/usr/bin/env python3
"""
Rebuilds js/sources/wide-portraits.js: which wide hero portraits ({code}_l.png, skins {code}_sNN_l.png) exist in the
community asset repository CeciliaBot/E7Assets-Temp (assets/face). The app downloads those pictures itself when it
reads a draft; this list only tells it which names exist (so it doesn't have to guess skins).

Get the file listing without downloading the pictures, then run this:

    git clone --depth 1 --filter=blob:none --no-checkout https://github.com/CeciliaBot/E7Assets-Temp /tmp/e7assets
    git -C /tmp/e7assets ls-tree -r HEAD --name-only > /tmp/e7assets-files.txt
    python3 tools/update-wide-list.py /tmp/e7assets-files.txt
"""
import datetime
import json
import os
import re
import sys

names = [l.strip().split('/')[-1] for l in open(sys.argv[1]) if l.startswith('assets/face/')]
base = sorted(m.group(1) for f in names if (m := re.match(r'^(c\d{4})_l\.png$', f)))
skins = {}
for f in names:
    m = re.match(r'^(c\d{4})_s(\d\d)_l\.png$', f)
    if m:
        skins.setdefault(m.group(1), []).append(m.group(2))
if len(base) < 300:
    sys.exit('The listing looks incomplete - not overwriting.')
out = {"source": "CeciliaBot/E7Assets-Temp", "url": "https://github.com/CeciliaBot/E7Assets-Temp/tree/main/assets/face",
       "listedAt": datetime.date.today().isoformat(), "base": base, "skins": {k: sorted(v) for k, v in sorted(skins.items())}}
dst = os.path.join(os.path.dirname(__file__), '..', 'js', 'sources', 'wide-portraits.js')
with open(dst, 'w') as f:
    f.write("/* AUTO-GENERATED by tools/update-wide-list.py — which wide hero portraits (pick cards) exist in the community asset repository. */\n")
    f.write("(function (root) {\n  const list = " + json.dumps(out, separators=(',', ':')) + ";\n")
    f.write("  if (typeof module !== 'undefined' && module.exports) module.exports = list;\n")
    f.write("  else (root.RTASources = root.RTASources || {}).widePortraits = list;\n})(typeof window !== 'undefined' ? window : globalThis);\n")
print('wide portraits:', len(base), 'heroes,', sum(len(v) for v in skins.values()), 'skins')
