#!/usr/bin/env python3
"""
Rebuilds js/sources/wide-portraits.js: which hero pictures exist in the community asset repository
CeciliaBot/E7Assets-Temp (assets/face):
  - wide portraits {code}_l.png and skins {code}_sNN_l.png (pick cards of the RTA draft)
  - round icons {code}_s.png and skins {code}_sNN_s.png (pre-ban icons, Guild War defense icons; DEVLOG #63: these
    are the game's current icons, the official site's are older artwork for about half of the heroes)
The app downloads those pictures itself when it reads the game; this list only tells it which names exist.

Get the file listing without downloading the pictures, then run this:

    git clone --depth 1 --filter=blob:none --no-checkout https://github.com/CeciliaBot/E7Assets-Temp /tmp/e7assets
    git -C /tmp/e7assets ls-tree -r HEAD --name-only > /tmp/e7assets-files.txt
    python3 tools/update-wide-list.py /tmp/e7assets-files.txt
"""
import datetime
import json
import os
import re
import sys

names = [l.strip().split('/')[-1] for l in open(sys.argv[1]) if l.startswith('assets/face/')]
base = sorted(m.group(1) for f in names if (m := re.match(r'^(c\d{4})_l\.png$', f)))
skins = {}
for f in names:
    m = re.match(r'^(c\d{4})_s(\d\d)_l\.png$', f)
    if m:
        skins.setdefault(m.group(1), []).append(m.group(2))
icons = sorted(m.group(1) for f in names if (m := re.match(r'^(c\d{4})_s\.png$', f)))
icon_skins = {}
for f in names:
    m = re.match(r'^(c\d{4})_s(\d\d)_s\.png$', f)
    if m:
        icon_skins.setdefault(m.group(1), []).append(m.group(2))
if len(base) < 300 or len(icons) < 300:
    sys.exit('The listing looks incomplete - not overwriting.')
out = {"source": "CeciliaBot/E7Assets-Temp", "url": "https://github.com/CeciliaBot/E7Assets-Temp/tree/main/assets/face",
       "listedAt": datetime.date.today().isoformat(), "base": base, "skins": {k: sorted(v) for k, v in sorted(skins.items())},
       "icons": icons, "iconSkins": {k: sorted(v) for k, v in sorted(icon_skins.items())}}
dst = os.path.join(os.path.dirname(__file__), '..', 'js', 'sources', 'wide-portraits.js')
with open(dst, 'w') as f:
    f.write("/* AUTO-GENERATED by tools/update-wide-list.py — which hero pictures (wide portraits for pick cards, round icons) exist in the community asset repository. */\n")
    f.write("(function (root) {\n  const list = " + json.dumps(out, separators=(',', ':')) + ";\n")
    f.write("  if (typeof module !== 'undefined' && module.exports) module.exports = list;\n")
    f.write("  else (root.RTASources = root.RTASources || {}).widePortraits = list;\n})(typeof window !== 'undefined' ? window : globalThis);\n")
print('wide portraits:', len(base), 'heroes,', sum(len(v) for v in skins.values()), 'skins · round icons:', len(icons), 'heroes,', sum(len(v) for v in icon_skins.values()), 'skins')
