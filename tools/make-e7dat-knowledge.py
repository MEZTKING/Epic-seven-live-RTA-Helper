#!/usr/bin/env python3
"""
Builds js/sources/e7dat-knowledge.js from E7DaT's hero knowledge file (github.com/ohrgon-game/E7DaT, MIT,
e7draft/assets/knowledge.json): mechanic tags per hero, the "what blocks what" rules, how top players build each hero
(artifact + sets, share, start CR), who usually moves first. English texts only; Korean build strings are translated
with the file's own tables. Kept as its own source ('E7DaT knowledge'), switchable in the app. See docs/SOURCES.md.

    python3 tools/make-e7dat-knowledge.py <path to E7DaT>/e7draft/assets/knowledge.json
"""
import json
import os
import re
import sys

k = json.load(open(sys.argv[1], encoding='utf-8'))
arts_en = dict(k.get('artifacts_en', {}))
for code, a in k.get('arts', {}).items():
    arts_en[a[0]] = a[1]
sets_en = k.get('sets_en', {})
untranslated = set()


def tr_set(tok):
    m = re.match(r'^(.*?)(\d*)$', tok.strip())
    name, n = m.group(1), m.group(2)
    en = sets_en.get(name) or sets_en.get(tok.strip())
    if not en:
        untranslated.add(tok)
        en = name
    return en + (' ×' + n if n else '')


def variant(v):
    text, share, cr, guard = v
    art, _, sets = text.partition(' + ')
    art_en = arts_en.get(art.strip())
    if not art_en:
        untranslated.add(art)
        art_en = art.strip()
    return [art_en, [tr_set(t) for t in sets.split('·') if t.strip()], share, cr, guard]


rules = []
for i, r in enumerate(k['rules']):
    en = k['rules_en'][i]
    rules.append({"by": r[0], "on": r[1], "text": en[0], "hurt": en[1], "warn": bool(r[3]), "strict": i in set(k.get('strict', []))})

art_name = {code: a[1] for code, a in k.get('arts', {}).items()}
art_effect = {code: a[3] for code, a in k.get('arts', {}).items()}
out = {
    "source": "E7DaT knowledge",
    "url": "https://github.com/ohrgon-game/E7DaT",
    "date": k.get('date', ''),
    "basis": "Mechanics from skill descriptions; multipliers and win-rate differences from 40,300 Legend/Emperor games up to 2026-11-12; builds from the top 100 players' games (1-12 Nov 2026). A fixed snapshot: it does not update.",
    "labels": k['labels_en'],
    "rules": rules,
    "tags": k['tags'],
    "tagFromArtifact": {c: {t: art_name.get(a, a) for t, a in d.items()} for c, d in k.get('tagsrc', {}).items()},
    "hurt": k.get('hurt', {}),
    "lift": k.get('lift', {}),
    "pairLift": k.get('pairlift', {}),
    "pairAvoid": k.get('pairavoid', {}),
    "variants": {c: [variant(v) for v in vs] for c, vs in k.get('variants', {}).items()},
    "openers": k.get('openers', []),
    "imprint": k.get('imprint', {}),
    "heroArtifacts": {c: [[art_name.get(a, a), share, art_effect.get(a, '')] for a, share in lst] for c, lst in k.get('hero_arts', {}).items()},
    "exclusive": k.get('exclusive_en', {}),
}
dst = os.path.join(os.path.dirname(__file__), '..', 'js', 'sources', 'e7dat-knowledge.js')
with open(dst, 'w', encoding='utf-8') as f:
    f.write("/* AUTO-GENERATED by tools/make-e7dat-knowledge.py — hero mechanics, rules and top-player builds from E7DaT's knowledge.json (MIT). */\n")
    f.write("(function (root) {\n  const knowledge = " + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ";\n")
    f.write("  if (typeof module !== 'undefined' && module.exports) module.exports = knowledge;\n")
    f.write("  else (root.RTASources = root.RTASources || {}).e7datKnowledge = knowledge;\n})(typeof window !== 'undefined' ? window : globalThis);\n")
print('heroes with tags', len(out['tags']), 'rules', len(rules), 'builds for', len(out['variants']), 'openers', len(out['openers']))
print('not translated (kept as is):', sorted(untranslated))
