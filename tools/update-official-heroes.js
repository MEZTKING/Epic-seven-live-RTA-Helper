#!/usr/bin/env node
/*
 * Regenerates js/sources/official-heroes.js from Smilegate's public hero list.
 *
 *   node tools/update-official-heroes.js                 # downloads the list
 *   node tools/update-official-heroes.js path/to/file.json  # uses a saved copy
 *
 * The app also refreshes this list itself in the browser (Data tab); this
 * snapshot only makes the app work offline / on first load.
 */
const fs = require('fs');
const path = require('path');
const { normalizeOfficial, OFFICIAL_HERO_URL } = require('../js/roster.js');

async function main() {
  const file = process.argv[2];
  const raw = file ? JSON.parse(fs.readFileSync(file, 'utf8')) : await (await fetch(OFFICIAL_HERO_URL)).json();
  const heroes = normalizeOfficial(raw, 'en');
  if (heroes.length < 100) throw new Error(`Only ${heroes.length} heroes parsed — refusing to overwrite snapshot.`);
  const out = path.join(__dirname, '..', 'js', 'sources', 'official-heroes.js');
  const body =
    '/* AUTO-GENERATED by tools/update-official-heroes.js — do not edit by hand.\n' +
    ` * Source: ${OFFICIAL_HERO_URL}\n */\n` +
    '(function (root) {\n' +
    `  const snapshot = ${JSON.stringify({ source: 'official', url: OFFICIAL_HERO_URL, fetchedAt: new Date().toISOString(), heroes })};\n` +
    "  if (typeof module !== 'undefined' && module.exports) module.exports = snapshot;\n" +
    '  else (root.RTASources = root.RTASources || {}).officialSnapshot = snapshot;\n' +
    "})(typeof window !== 'undefined' ? window : globalThis);\n";
  fs.writeFileSync(out, body);
  console.log(`Wrote ${heroes.length} heroes to ${path.relative(process.cwd(), out)}`);
}
main().catch((e) => {
  console.error(e.message);
  process.exit(1);
});
