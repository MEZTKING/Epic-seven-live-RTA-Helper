#!/usr/bin/env python3
"""
Builds js/sources/draft-labels.js: small greyscale templates of the World Arena draft screen's stage texts
("Your Turn", "Opponent's Turn", "BAN", "Ready", "First Pick", "Select Pre-Ban Hero") in English, Korean and Japanese,
with the boxes they sit in.

Source: the screen-text crops and boxes of E7DaT (github.com/ohrgon-game/E7DaT, e7draft/assets/<lang>/ and
e7draft/layout.py; code MIT, the crops are game screen elements owned by Smilegate / Super Creative and are used here,
as there, only to recognise the draft stage). See docs/SOURCES.md.

    python3 tools/make-draft-labels.py <path to E7DaT>/e7draft/assets

Every template is stored at the size it has on a screen CANON_W pixels wide (so one scale works for any window).
Needs Pillow.
"""
import base64
import json
import os
import sys
from datetime import date

from PIL import Image

CANON_W = 1024
# boxes (x, y, w, h) as fractions of the 16:9 game picture; Korean ones from layout.py, others from <lang>/screen.json
KO = {"label_box": (0.335, 0.020, 0.135, 0.050), "popup_preban_box": (0.058, 0.100, 0.155, 0.050),
      "first_pick_box": {"me": (0.1660, 0.9195, 0.1191, 0.0444), "enemy": (0.7156, 0.9187, 0.1191, 0.0444)}}
LABELS = {"label_turn_me": "turn_me", "label_turn_enemy": "turn_enemy", "label_ban": "ban", "label_ready": "ready"}


def tpl(path, box_w):
    im = Image.open(path).convert("L")
    w = max(8, round(box_w * CANON_W))
    h = max(4, round(im.size[1] * w / im.size[0]))
    im = im.resize((w, h), Image.LANCZOS)
    return {"w": w, "h": h, "px": base64.b64encode(im.tobytes()).decode()}


def main(assets):
    out = {"source": "E7DaT", "url": "https://github.com/ohrgon-game/E7DaT", "builtAt": date.today().isoformat(),
           "canonW": CANON_W, "langs": {}}
    for lang in ("en", "ko", "ja"):
        d = os.path.join(assets, lang)
        meta = {}
        mp = os.path.join(d, "screen.json")
        if os.path.exists(mp):
            meta = json.load(open(mp, encoding="utf-8-sig"))
        box = tuple(meta.get("label_box") or KO["label_box"])
        L = {"name": meta.get("name") or lang, "labelBox": box, "labelMin": float(meta.get("label_min") or 0.6),
             "labelColor": bool(meta.get("label_color")), "labels": {}}
        for f, name in LABELS.items():
            L["labels"][name] = tpl(os.path.join(d, f + ".png"), box[2])
        pb = tuple(meta.get("popup_preban_box") or KO["popup_preban_box"])
        if os.path.exists(os.path.join(d, "popup_preban.png")):
            L["prebanPopup"] = {"box": pb, **tpl(os.path.join(d, "popup_preban.png"), pb[2])}
        fp = meta.get("first_pick_box") or KO["first_pick_box"]
        if os.path.exists(os.path.join(d, "label_first_pick.png")):
            L["firstPick"] = {"boxes": {k: tuple(v) for k, v in fp.items()}, **tpl(os.path.join(d, "label_first_pick.png"), fp["me"][2])}
        out["langs"][lang] = L
    dst = os.path.join(os.path.dirname(__file__), "..", "js", "sources", "draft-labels.js")
    with open(dst, "w", encoding="utf-8") as f:
        f.write("/* AUTO-GENERATED by tools/make-draft-labels.py — draft stage text templates (from E7DaT's screen-text crops). */\n")
        f.write("(function (root) {\n  const labels = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n")
        f.write("  if (typeof module !== 'undefined' && module.exports) module.exports = labels;\n")
        f.write("  else (root.RTASources = root.RTASources || {}).draftLabels = labels;\n})(typeof window !== 'undefined' ? window : globalThis);\n")
    print("wrote", dst, {k: list(v["labels"]) for k, v in out["langs"].items()})


if __name__ == "__main__":
    main(sys.argv[1])
