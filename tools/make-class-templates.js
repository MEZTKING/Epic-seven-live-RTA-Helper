#!/usr/bin/env node
/*
 * Builds js/sources/class-templates.js: examples of the class symbols (thief, ranger, warrior, mage, knight,
 * soul weaver) cut from a REAL Steam screenshot (tests/fixtures/screens/steam-rta-preban-select.png), from the
 * 15 heroes on it that were confirmed by eye (DEVLOG #23). Uses the same browser code as the app (js/faces.js),
 * so the numbers match what the app computes. Needs Playwright (Chromium): node tools/make-class-templates.js
 * Add more examples (more screenshots, more heroes) by extending KNOWN below.
 */
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');

const ROOT = path.join(__dirname, '..');
const SHOT = path.join(ROOT, 'tests/fixtures/screens/steam-rta-preban-select.png');
// grid cell [row, col] -> hero name (pre-ban picker: icon centre x = 127 + col*96.2, y = 175 + row*103; ring box 84 px)
const KNOWN = {
  '2,2': 'Swift Flagbearer Sigret', '2,3': 'School Nurse Yulha', '2,4': 'Saria', '2,6': 'Stark', '2,7': 'Frieren', '2,9': 'Lady of the Scales',
  '3,0': 'Genesis Ras', '3,1': 'Aram', '3,2': 'Witch of the Mere Tenebria', '3,3': 'Argent Waves Hwayoung', '3,5': 'Robin', '3,6': 'Rinak',
  '3,7': 'Boss Arunka', '3,8': 'Guard Captain Krau', '3,9': 'Successor Taeyou',
};

(async () => {
  const heroes = require(path.join(ROOT, 'js/sources/official-heroes.js')).heroes;
  const byName = new Map(heroes.map((h) => [h.name, h]));
  const b = await chromium.launch();
  const p = await b.newPage();
  await p.setContent('<body></body>');
  await p.addScriptTag({ path: path.join(ROOT, 'js/faces.js') });
  const img = 'data:image/png;base64,' + fs.readFileSync(SHOT).toString('base64');
  const cells = Object.keys(KNOWN).map((k) => k.split(',').map(Number));
  const vecs = await p.evaluate(async ({ img, cells }) => {
    const im = new Image();
    await new Promise((r) => { im.onload = r; im.src = img; });
    return cells.map(([r, c]) => {
      const cx = 127 + c * 96.2, cy = 175 + r * 103;
      const all = window.RTAFaces.classVectorsAt(im, { x: cx - 42, y: cy - 44, w: 84, h: 84 });
      return Array.from(all[4], (v) => Math.round(v * 1000) / 1000); // the unshifted one
    });
  }, { img, cells });
  await b.close();
  const templates = Object.values(KNOWN).map((name, i) => ({ role: byName.get(name).role, from: name, vec: vecs[i] }));
  const out = `/* AUTO-GENERATED by tools/make-class-templates.js from tests/fixtures/screens/steam-rta-preban-select.png
 * Class symbols (16×16 grey, zero-mean, unit length) of ${templates.length} heroes confirmed by eye. Roles: ${[...new Set(templates.map((t) => t.role))].join(', ')}.
 */
(function (root) {
  const templates = ${JSON.stringify(templates)};
  if (typeof module !== 'undefined' && module.exports) module.exports = templates;
  else (root.RTASources = root.RTASources || {}).classTemplates = templates;
})(typeof window !== 'undefined' ? window : globalThis);
`;
  fs.writeFileSync(path.join(ROOT, 'js/sources/class-templates.js'), out);
  console.log(`wrote js/sources/class-templates.js: ${templates.length} examples (${templates.map((t) => t.role).join(', ')})`);
})();
